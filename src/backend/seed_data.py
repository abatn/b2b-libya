def seed_database():
    """Seed the database with suppliers and products."""
    db = SessionLocal()
    try:
        # Check if already seeded
        existing = db.query(Supplier).count()
        if existing > 0:
            print(f"Database already has {existing} suppliers. Skipping seed.")
            return

        print("Seeding database...")

        # Create admin user if needed
        from services.auth import hash_password as _pw_hash  # noqa: E402

        admin = db.query(User).filter(User.username == "admin").first()
        if not admin:
            admin = User(
                username="admin",
                email="admin@libya-b2b.ly",
                password_hash=_pw_hash("admin123"),
                role="admin",
                business_name="Libya B2B Admin",
            )
            db.add(admin)
            db.flush()

        # Create seller users and suppliers
        supplier_map = {}  # name → (user_id, supplier_id)
        for i, s in enumerate(SUPPLIERS):
            # Create seller user
            seller_user = User(
                username=f"supplier_{i + 1:03d}",
                email=f"{s['name'].lower().replace(' ', '_')}@libya-b2b.ly",
                password_hash=_pw_hash("supplier123"),
                role="seller",
                business_name=s["name"],
                business_name_arabic=s.get("name_arabic"),
                phone=s.get("phone"),
            )
            db.add(seller_user)
            db.flush()

            # Create supplier profile
            supplier = Supplier(
                user_id=seller_user.id,
                name=s["name"],
                name_arabic=s.get("name_arabic"),
                description=s.get("description"),
                city=s.get("city"),
                phone=s.get("phone"),
                website=s.get("website"),
                category=s.get("category"),
                categories=json.dumps(SUPPLIER_CATEGORIES.get(s["name"], [s.get("category")])),
                is_verified=True,
                verification_level=4,
                verified_at=datetime.now(timezone.utc),
                verified_by=admin.id,
                logo_url=SUPPLIER_LOGOS.get(s["name"]),
                years_on_platform=max(1, 2026 - s.get("year_established", 2020)),
                employee_count=s.get("employee_count"),
                year_established=s.get("year_established"),
                rating=round(3.5 + (i % 15) * 0.1, 1),  # 3.5-4.9
                rating_count=5 + (i % 20),
                total_transactions=10 + (i % 50),
                response_time_hours=2 + (i % 24),
                on_time_delivery_rate=round(85 + (i % 15), 1),
            )
            db.add(supplier)
            db.flush()

            supplier_map[s["name"]] = (seller_user.id, supplier.id)
            print(f"  [{i + 1:2d}/30] {s['name']} → user#{seller_user.id} supplier#{supplier.id}")

        # Create products
        product_count = 0
        for i, p in enumerate(PRODUCTS):
            # Find a supplier in the same category
            supplier_name = None
            for s_name, (uid, sid) in supplier_map.items():
                s_data = next((s for s in SUPPLIERS if s["name"] == s_name), None)
                if s_data and s_data["category"] == p["category"]:
                    supplier_name = s_name
                    break
            if not supplier_name:
                # Fallback: use first supplier
                supplier_name = list(supplier_map.keys())[0]

            uid, sid = supplier_map[supplier_name]
            product = Product(
                name=p["name"],
                name_arabic=p.get("name_arabic"),
                category=p["category"],
                price=p["price"],
                moq=p.get("moq", 1),
                stock_quantity=p.get("stock", 100),
                seller_id=uid,
                is_active=True,
                image_url=PRODUCT_IMAGES.get(p["name"], CATEGORY_IMAGES.get(p["category"], "https://m.media-amazon.com/images/I/91lP2eOp7LL._AC_UL320_.jpg")),
            )
            db.add(product)
            product_count += 1

        db.commit()
        print(f"\nSeeded: {len(SUPPLIERS)} suppliers, {product_count} products")
        print("Database ready!")

    except Exception as e:
        db.rollback()
        print(f"Error seeding database: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    Base.metadata.create_all(bind=engine)
    seed_database()
